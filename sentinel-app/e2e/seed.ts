#!/usr/bin/env node
/**
 * Seeds the E2E test environment against the real production services.
 *
 * Run once before the first `npm run test:e2e`:
 *   npx tsx e2e/seed.ts
 *
 * What it does:
 *   1. Creates a dedicated test account on control.thesentinels.online (signup).
 *      If the account already exists it simply logs in instead.
 *   2. Verifies the JWT works (GET /auth/me).
 *   3. Writes .env.test with the correct URLs and credentials so tests can
 *      authenticate without any manual config.
 */

import { writeFileSync } from "fs";
import { join } from "path";

const CONTROL_URL = "https://control.thesentinels.online";
const APP_URL     = "https://app.thesentinels.online";

// Dedicated throwaway account — safe to commit these since it's a test-only
// tenant with no real cameras or sensitive data.
const TEST_EMAIL    = "e2e-sentinel@thesentinels.online";
const TEST_PASSWORD = "E2eTest!2025";
const TENANT_NAME   = "E2E Test Tenant";

async function post(path: string, body: unknown, token?: string) {
  const headers: Record<string, string> = { "Content-Type": "application/json" };
  if (token) headers["Authorization"] = `Bearer ${token}`;
  const res = await fetch(`${CONTROL_URL}${path}`, {
    method: "POST",
    headers,
    body: JSON.stringify(body),
  });
  return { status: res.status, body: await res.json().catch(() => ({})) };
}

async function main() {
  console.log("Seeding E2E test environment → " + CONTROL_URL);

  // 1. Try signup — expect 200 (created) or 409 (already exists).
  console.log("  Signing up test account…");
  const signup = await post("/auth/signup", {
    tenant_name: TENANT_NAME,
    email:       TEST_EMAIL,
    password:    TEST_PASSWORD,
  });

  let token: string;

  if (signup.status === 200 || signup.status === 201) {
    token = (signup.body as { token: string }).token;
    console.log("  ✓ Account created.");
  } else if (signup.status === 409) {
    // Already exists — log in instead.
    console.log("  Account exists — logging in…");
    const login = await post("/auth/login", { email: TEST_EMAIL, password: TEST_PASSWORD });
    if (login.status !== 200) {
      throw new Error(`Login failed (${login.status}): ${JSON.stringify(login.body)}`);
    }
    token = (login.body as { token: string }).token;
    console.log("  ✓ Logged in.");
  } else {
    throw new Error(`Signup failed (${signup.status}): ${JSON.stringify(signup.body)}`);
  }

  // 2. Verify the token works.
  const me = await fetch(`${CONTROL_URL}/auth/me`, {
    headers: { Authorization: `Bearer ${token}` },
  });
  if (!me.ok) throw new Error(`/auth/me failed (${me.status})`);
  const meBody = await me.json() as { email: string };
  console.log(`  ✓ Token valid — authenticated as ${meBody.email ?? TEST_EMAIL}`);

  // 3. Write .env.test — include the token so tests can call the API
  //    without reading localStorage (which is unavailable before page.goto).
  const envPath = join(import.meta.dirname, "../.env.test");
  const envContent = [
    `# Auto-generated by e2e/seed.ts — do not commit`,
    `E2E_BASE_URL=${APP_URL}`,
    `E2E_CONTROL_URL=${CONTROL_URL}`,
    `E2E_EMAIL=${TEST_EMAIL}`,
    `E2E_PASSWORD=${TEST_PASSWORD}`,
    `E2E_TOKEN=${token}`,
  ].join("\n") + "\n";

  writeFileSync(envPath, envContent, "utf-8");
  console.log(`  ✓ Written .env.test`);
  console.log("\nDone. Run tests with:\n  npm run test:e2e");
}

main().catch((err) => {
  console.error("Seed failed:", err.message);
  process.exit(1);
});
